<?php

namespace Tests\Feature\Admin\Settings;

use App\Models\Accountant;
use App\Models\Admin;
use App\Models\Kitchen;
use App\Models\User;
use App\Models\Worker;
use App\Providers\SettingsServiceProvider;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Storage;
use Tests\TestCase;
use ElCoop\Valuestore\Valuestore;
use Illuminate\Foundation\Testing\WithFaker;
use Illuminate\Foundation\Testing\RefreshDatabase;

class SettingsTest extends TestCase {
	use RefreshDatabase;
	use WithFaker;
	protected $admin;
	protected $kitchen;
	protected $worker;
	protected $accountant;

	protected function setUp(): void {
		parent::setUp(); // TODO: Change the autogenerated stub
		$this->admin = Admin::factory()->create();
		$this->admin->user()->save(User::factory()->make());
		$this->accountant = User::factory()->make();
		Accountant::factory()->create()->user()->save($this->accountant);
		$this->worker = User::factory()->make();
		Worker::factory()->create()->user()->save($this->worker);
		$this->kitchen = Kitchen::factory()->create();
		$this->kitchen->user()->save(User::factory()->make());
		Storage::fake('local');
		Storage::disk('local')->put('test.valuestore.json', '');
		$path = Storage::path('test.valuestore.json');
		$this->app->singleton('settings', function ($app) use ($path) {
			return new Valuestore($path);
		});
		$faker = $this->faker;
		$settings = app('settings');
		$settings->put('accountant_email', $faker->email);
		$settings->put('accountant_password', '');
		$settings->put('general_registration_status', false);
		$settings->put('general_application_text_en', $faker->text);
		$settings->put('general_application_text_nl', $faker->text);
		$settings->put('general_registration_text_nl', $faker->text);
		$settings->put('general_registration_text_en', $faker->text);
		$settings->put('general_login_text_en', $faker->text);
		$settings->put('general_login_text_nl', $faker->text);
		$settings->put('registration_year', 2019);
		$settings->put('schedule_budget', 0);
		$settings->put('application_drinks_fee', 1000);
	}

	public function test_guest_cant_see_page() {
		$this->get(action('Admin\SettingsController@show'))->assertRedirect(action('Auth\LoginController@login'));
	}

	public function test_worker_cant_see_page() {
		$this->actingAs($this->worker)->get(action('Admin\SettingsController@show'))->assertForbidden();
	}

	public function test_kitchen_cant_see_page() {
		$this->actingAs($this->kitchen->user)->get(action('Admin\SettingsController@show'))->assertForbidden();
	}

	public function test_accountant_cant_see_page() {
		$this->actingAs($this->accountant)->get(action('Admin\SettingsController@show'))->assertForbidden();
	}

	public function test_admin_can_see_page() {
		$this->actingAs($this->admin->user)->get(action('Admin\SettingsController@show'))
			->assertStatus(200)
			->assertSee(__('admin/settings.accountant'));
	}

	public function test_guest_cant_update_settings() {
		$this->patch(action('Admin\SettingsController@update'), [
			'accountant_email' => 'test@test.com',
			'general_application_text_en' => 'test',
			'general_application_text_nl' => 'testtest',
			'general_registration_text_en' => 'regtest',
			'general_registration_text_nl' => 'regtestnl',
			'general_login_text_en' => 'logintest',
			'general_login_text_nl' => 'logintestnl'
		])->assertRedirect(action('Auth\LoginController@login'));
	}

	public function test_worker_cant_update_settings() {
		$this->actingAs($this->worker)->patch(action('Admin\SettingsController@update'), [
			'accountant_email' => 'test@test.com',
			'general_application_text_en' => 'test',
			'general_application_text_nl' => 'testtest',
			'general_registration_text_en' => 'regtest',
			'general_registration_text_nl' => 'regtestnl',
			'general_login_text_en' => 'logintest',
			'general_login_text_nl' => 'logintestnl'
		])->assertForbidden();
	}

	public function test_kitchen_cant_update_settings() {
		$this->actingAs($this->kitchen->user)->patch(action('Admin\SettingsController@update'), [
			'accountant_email' => 'test@test.com',
			'general_application_text_en' => 'test',
			'general_application_text_nl' => 'testtest',
			'general_registration_text_en' => 'regtest',
			'general_registration_text_nl' => 'regtestnl',
			'general_login_text_en' => 'logintest',
			'general_login_text_nl' => 'logintestnl'
		])->assertForbidden();
	}

	public function test_accountant_cant_update_settings() {
		$this->actingAs($this->accountant)->patch(action('Admin\SettingsController@update'), [
			'accountant_email' => 'test@test.com',
			'general_application_text_en' => 'test',
			'general_application_text_nl' => 'testtest',
			'general_registration_text_en' => 'regtest',
			'general_registration_text_nl' => 'regtestnl',
			'general_login_text_en' => 'logintest',
			'general_login_text_nl' => 'logintestnl'
		])->assertForbidden();
	}

	public function test_admin_can_update_settings() {
		$settings = [
			'accountant_email' => 'test@test.com',
			'accountant_password' => '123456',
			'general_application_text_en' => 'test',
			'general_application_text_nl' => 'testtest',
			'general_registration_text_en' => 'regtest',
			'general_registration_text_nl' => 'regtestnl',
			'general_login_text_en' => 'logintest',
			'general_login_text_nl' => 'logintestnl',
			'registration_year' => '2019',
			'schedule_budget' => '100',
			'application_drinks_fee' => '1200',
		];
		$this->actingAs($this->admin->user)->patch(action('Admin\SettingsController@update'), $settings)->assertRedirect();
		$settings['general_registration_status'] = false;
		$settings['accountant_password'] = '';
		$this->assertEquals($settings, $this->app->settings->all());
		$this->assertDatabaseHas('users', [
			'id' => $this->accountant->id,
			'email' => 'test@test.com',
		]);
		$accountant = User::where('user_type', Accountant::class)->first();
		$this->assertTrue(Hash::check('123456', $accountant->password));
	}

	public function test_admin_cant_update_settings_with_invalid_drinks_fee() {
		$this->actingAs($this->admin->user)->patch(action('Admin\SettingsController@update'), [
			'accountant_email' => 'test@test.com',
			'schedule_budget' => '100',
			'application_drinks_fee' => 'abc',
		])->assertRedirect()->assertSessionHasErrors('application_drinks_fee');
		$this->assertEquals(1000, $this->app->settings->get('application_drinks_fee'));
	}

	public function test_missing_settings_get_their_defaults() {
		Storage::disk('local')->put('test.valuestore.json', '');
		$this->app->getProvider(SettingsServiceProvider::class)->addMissingDefaults();

		foreach (config('settingsDefaults') as $key => $value) {
			$this->assertEquals($value, $this->app->settings->get($key));
		}
	}

	public function test_existing_settings_are_not_overwritten_by_defaults() {
		$this->app->settings->put('application_drinks_fee', 1200);
		$this->app->settings->put('application_selected_subject_nl', 'Eigen onderwerp');
		$this->app->settings->put('invoices_notes_nl', '');
		$this->app->settings->put('invoices_notes_en', null);
		$this->app->settings->put('application_waste_processing_fee', '290');
		$before = $this->app->settings->all();

		$this->app->getProvider(SettingsServiceProvider::class)->addMissingDefaults();

		$after = $this->app->settings->all();
		$this->assertEquals($before, array_intersect_key($after, $before));
		$this->assertEquals(array_diff_key(config('settingsDefaults'), $before), array_diff_key($after, $before));
	}

	public function test_defaults_dont_change_complete_settings() {
		$complete = config('settingsDefaults');
		$complete['application_selected_subject_nl'] = 'Eigen onderwerp';
		Storage::disk('local')->put('test.valuestore.json', json_encode($complete));
		$file = Storage::disk('local')->get('test.valuestore.json');

		$this->app->getProvider(SettingsServiceProvider::class)->addMissingDefaults();

		$this->assertEquals($file, Storage::disk('local')->get('test.valuestore.json'));
	}

	public function test_admin_sees_added_default_settings() {
		$this->app->getProvider(SettingsServiceProvider::class)->addMissingDefaults();

		$this->actingAs($this->admin->user)->get(action('Admin\SettingsController@show'))
			->assertStatus(200)
			->assertSee('name="application_selected_subject_nl"', false)
			->assertSee(config('settingsDefaults.application_selected_subject_nl'));
	}
}
